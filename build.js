#!/usr/bin/env node
/**
 * build.js — bundles the multi-file PWA into one portable HTML file.
 *
 *   node build.js
 *
 * Output: dist/EnerFab-Biomass-Storage.html
 * One file, no network, no server: double-click it on any site laptop and
 * the whole system opens. Useful for previewing, for USB sticks, and for
 * emailing to a manager who cannot install anything.
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = __dirname;
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');

let html = read('index.html');
const css = read('css/app.css');
const logo = fs.readFileSync(path.join(ROOT, 'assets/enerfab-logo.png')).toString('base64');
const logoUri = `data:image/png;base64,${logo}`;

// Every replacement below uses a *function* so that "$" sequences inside the
// CSS/JS are never interpreted as replacement patterns.
const put = (needle, content) => { html = html.replace(needle, () => content); };

// 1. stylesheet -> inline
put('<link rel="stylesheet" href="css/app.css" />', `<style>\n${css}\n</style>`);

// 3. scripts -> inline, in order
const scriptRe = /<script src="(js\/[^"]+)"><\/script>/g;
const scripts = [];
html = html.replace(scriptRe, (_m, src) => {
  scripts.push(src);
  return `<!-- inline:${src} -->`;
});
const bundle = scripts.map((src) => `\n/* ===== ${src} ===== */\n${read(src)}`).join('\n');
// a literal </script> inside a string would terminate the tag early
const safeBundle = bundle.replace(/<\/script/gi, '<\\/script');
put('<!-- inline:js/config.js -->', `<script>\n${safeBundle}\n</script>`);
html = html.replace(/<!-- inline:js\/[^>]+?-->\n?/g, '');

// 4. a single file cannot register a service worker; drop the manifest link
html = html.replace(/<link rel="manifest"[^>]*>\s*/, '');
html = html.replace(/<link rel="icon"[^>]*>\s*/, '');
html = html.replace(/<link rel="apple-touch-icon"[^>]*>\s*/, '');
html = html.replace(
  /if \('serviceWorker' in navigator && location\.protocol\.startsWith\('http'\)\) \{[\s\S]*?\}\n/,
  () => '/* single-file build: no service worker */\n',
);

// 5. a note in the head so nobody mistakes it for the deployable copy
html = html.replace('<title>', '<!-- Single-file build generated by build.js — the multi-file PWA lives in this folder -->\n  <title>');

// 6. logo -> data URI (done last so the copies inside the JS templates are
//    caught as well as the ones in the markup)
html = html.split('assets/enerfab-logo.png').join(logoUri);

const outDir = path.join(ROOT, 'dist');
fs.mkdirSync(outDir, { recursive: true });
const outFile = path.join(outDir, 'EnerFab-Biomass-Storage.html');
fs.writeFileSync(outFile, html, 'utf8');

const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
console.log(`Built ${path.relative(ROOT, outFile)}  ${kb(Buffer.byteLength(html))}`);
console.log(`Inlined: css/app.css (${kb(css.length)}), ${scripts.length} scripts (${kb(bundle.length)}), logo (${kb(logo.length)})`);
